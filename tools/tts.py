# tts.py: narration for a scene. Speaks a text with edge-tts and writes, side by side in assets/narration/:
#   <name>.mp3  the voice (mux it in with render.mjs --audio=assets/narration/<name>.mp3)
#   <name>.js   NARRATION.<name> = { audio, duration, words: [{ w, t0, t1 }] }: every spoken word, with the punctuation
#               around it, and when it starts and ends (s). Load it in studio.html after src/captions.js.
#
#   ../.venv/bin/python tools/tts.py --name=kapi --text="Gece yarısını geçiyordu. ..." [--fx=horror]
#   ../.venv/bin/python tools/tts.py --name=kapi --file=story/part1.txt [--rate=-10% --pitch=-4Hz]   (default: the voice as is)
#
# Voices: tr-TR-EmelNeural (default) and tr-TR-AhmetNeural (broken on Microsoft's side as of 2026-10-21).
# --fx=horror runs the voice through ffmpeg: a low-pass and a short echo. It doesn't change the timing.
import argparse, asyncio, json, os, subprocess, sys
import edge_tts

PUNCT_AFTER = '.,;:!?…"\'”’»)'
FX = {'horror': 'lowpass=f=6500,aecho=0.8:0.7:60|140:0.25|0.15,volume=1.2'}

ap = argparse.ArgumentParser()
ap.add_argument('--name', required=True)
ap.add_argument('--text')
ap.add_argument('--file')
ap.add_argument('--voice', default='tr-TR-EmelNeural')
ap.add_argument('--rate', default='+0%')
ap.add_argument('--pitch', default='+0Hz')
ap.add_argument('--fx', choices=list(FX))
ap.add_argument('--out', default='assets/narration')
a = ap.parse_args()
text = a.text if a.text else open(a.file, encoding='utf-8').read() if a.file else sys.exit('pass --text or --file')
text = ' '.join(text.split())


def attach(text, said):
    # Find each spoken word in the source text, in order, and widen it to the punctuation touching it ("kapı" → "kapı,").
    out, cur = [], 0
    for w, t0, t1 in said:
        i = text.find(w, cur)
        if i < 0: out.append({'w': w, 't0': t0, 't1': t1}); continue
        s, e = i, i + len(w)
        while s > cur and not text[s - 1].isspace(): s -= 1          # opening quotes, dashes
        while e < len(text) and text[e] in PUNCT_AFTER: e += 1
        out.append({'w': text[s:e], 't0': t0, 't1': t1}); cur = e
    return out


async def speak(path):
    said = []
    c = edge_tts.Communicate(text, a.voice, rate=a.rate, pitch=a.pitch, boundary='WordBoundary')
    with open(path, 'wb') as f:
        async for ch in c.stream():
            if ch['type'] == 'audio': f.write(ch['data'])
            elif ch['type'] == 'WordBoundary':
                t0 = ch['offset'] / 1e7; said.append((ch['text'], round(t0, 3), round(t0 + ch['duration'] / 1e7, 3)))
    return said


os.makedirs(a.out, exist_ok=True)
mp3 = f'{a.out}/{a.name}.mp3'
try:
    said = asyncio.run(speak(mp3))
except edge_tts.exceptions.NoAudioReceived:
    sys.exit(f'{a.voice} returned no audio: the voice may be down on Microsoft\'s side, try tr-TR-EmelNeural')
if a.fx:
    raw = mp3 + '.raw.mp3'; os.replace(mp3, raw)
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', raw, '-af', FX[a.fx], mp3], check=True); os.remove(raw)
dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', mp3], capture_output=True, text=True, check=True).stdout)
data = {'audio': mp3, 'duration': round(dur, 3), 'words': attach(text, said)}
with open(f'{a.out}/{a.name}.js', 'w', encoding='utf-8') as f:
    f.write(f'// generated by tools/tts.py ({a.voice}, rate {a.rate}, pitch {a.pitch}{", fx " + a.fx if a.fx else ""}): don\'t edit\n')
    f.write(f'NARRATION[{json.dumps(a.name)}] = {json.dumps(data, ensure_ascii=False)};\n')
print(f'{mp3}  {dur:.2f} s, {len(said)} words → {a.out}/{a.name}.js')
